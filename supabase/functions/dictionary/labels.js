export function localizeLabel(value,kind='用法'){
 const text=String(value??'').trim();if(!/[A-Za-z]/.test(text))return text;
 const known=Object.hasOwn(labels,text)?labels[text]:null;if(known)return known;
 if(/^Godan verb/i.test(text))return /special|irregular/i.test(text)?'五段动词（特殊）':'五段动词';
 if(/^Nidan verb/i.test(text))return '二段动词（古语）';
 if(/^Yodan verb/i.test(text))return '四段动词（古语）';
 return text;
}
export function localizeMeaningLabels(text){
 return String(text??'').replace(/〔([^〕]*)〕/g,(_,content)=>'〔'+[...new Set(content.split('・').map(v=>localizeLabel(v)))].join('・')+'〕');
}
